# 4. Model Loader
# ============================================
class ModelLoader:
    """Model loading and management."""

    @staticmethod
    def load_model(
        checkpoint_path: str,
        config: InferenceConfig
    ) -> nn.Module:
        """
        Load trained model from checkpoint.

        Args:
            checkpoint_path: Path to checkpoint file
            config: Inference configuration

        Returns:
            Loaded model in eval mode
        """
        if not os.path.exists(checkpoint_path):
            raise FileNotFoundError(f"Checkpoint not found: {checkpoint_path}")

        # Create model architecture
        model = models.mobilenet_v3_large(weights=None)
        model.classifier[3] = nn.Linear(
            in_features=1280,
            out_features=config.num_classes
        )

        # Load checkpoint
        checkpoint = torch.load(checkpoint_path, map_location=config.device)

        # Extract model state dict
        if 'model_state_dict' in checkpoint:
            model.load_state_dict(checkpoint['model_state_dict'])
            print(f"✅ Loaded model from epoch {checkpoint.get('epoch', 'N/A')}")
            print(f"   Best Validation Accuracy: {checkpoint.get('best_val_acc', 'N/A')}%")

            # Update class names if available
            if 'class_names' in checkpoint:
                config.class_names = checkpoint['class_names']
        else:
            model.load_state_dict(checkpoint)
            print("✅ Loaded model (direct state dict)")

        # Set to eval mode
        model = model.to(config.device)
        model.eval()

        return model



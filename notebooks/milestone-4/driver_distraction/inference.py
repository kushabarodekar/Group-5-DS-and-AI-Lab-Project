# 6. Main Predictor
# ============================================
class DriverActivityPredictor:
    """
    Driver Activity Classification Inference Pipeline.

    This class handles the complete inference pipeline:
    1. Image preprocessing
    2. Model inference
    3. Postprocessing
    4. Risk calculation
    """

    def __init__(
        self,
        checkpoint_path: str,
        config: Optional[InferenceConfig] = None,
        lazy_load: bool = False
    ):
        """
        Initialize the predictor.

        Args:
            checkpoint_path: Path to model checkpoint
            config: Inference configuration (optional)
            lazy_load: If True, load model on first prediction
        """
        self.checkpoint_path = checkpoint_path
        self.config = config or InferenceConfig()
        self._model = None
        self._preprocessor = None
        self._lazy_load = lazy_load

        # Initialize preprocessor
        self._preprocessor = ImagePreprocessor(self.config)

        # Load model immediately if not lazy loading
        if not lazy_load:
            self._load_model()

        print(f"✅ Predictor initialized on {self.config.device}")
        print(f"   Classes: {self.config.class_names}")

    def _load_model(self):
        """Load the model."""
        if self._model is None:
            self._model = ModelLoader.load_model(
                self.checkpoint_path,
                self.config
            )

    def _ensure_model_loaded(self):
        """Ensure model is loaded (for lazy loading)."""
        if self._model is None:
            self._load_model()

    def warmup(self) -> None:
        """
        Warmup the model by running dummy inference.
        This initializes CUDA kernels and allocates memory.
        """
        self._ensure_model_loaded()

        dummy_input = torch.randn(1, 3, 224, 224).to(self.config.device)

        with torch.no_grad():
            _ = self._model(dummy_input)

        # Clear cache
        if self.config.device == 'cuda':
            torch.cuda.empty_cache()

        print("✅ Model warmup complete")

    def unload(self) -> None:
        """
        Unload the model and release resources.
        """
        if self._model is not None:
            # Move to CPU before deletion
            self._model = self._model.to('cpu')
            del self._model
            self._model = None

            # Clear GPU cache
            if self.config.device == 'cuda':
                torch.cuda.empty_cache()

            print("✅ Model unloaded")

    def predict(
        self,
        image: Union[str, np.ndarray, Image.Image]
    ) -> Dict[str, Any]:
        """
        Predict driver activity from a single image.

        Args:
            image: Image path, numpy array (RGB), or PIL Image

        Returns:
            Prediction result dictionary
        """
        start_time = time.time()

        # Ensure model is loaded
        self._ensure_model_loaded()

        # Preprocess image
        input_tensor = self._preprocessor.preprocess(image)
        input_tensor = input_tensor.to(self.config.device)

        # Inference
        with torch.no_grad():
            if self.config.use_amp and self.config.device == 'cuda':
                with torch.cuda.amp.autocast():
                    outputs = self._model(input_tensor)
            else:
                outputs = self._model(input_tensor)

            probabilities = torch.softmax(outputs, dim=1)
            confidence, predicted = torch.max(probabilities, 1)

        # Get results
        predicted_index = predicted.item()
        predicted_class = self.config.class_names[predicted_index]
        confidence_score = confidence.item() * 100

        # Calculate risk score
        risk_score = RiskCalculator.calculate_risk(predicted_class, confidence_score)

        # Create metadata
        metadata = {
            'predicted_index': predicted_index,
            'probabilities': {
                self.config.class_names[i]: float(probabilities[0][i].item())
                for i in range(len(self.config.class_names))
            },
            'inference_time_ms': (time.time() - start_time) * 1000,
            'model_version': 'v1.0.0',
            'timestamp': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
            'device': self.config.device,
            'input_shape': input_tensor.shape
        }

        # Return result
        return {
            'module': 'Driver Activity Classification',
            'prediction': predicted_class,
            'confidence': confidence_score,
            'risk_score': risk_score,
            'metadata': metadata
        }

    def predict_batch(
        self,
        images: List[Union[str, np.ndarray, Image.Image]]
    ) -> List[Dict[str, Any]]:
        """
        Predict driver activity for multiple images.

        Args:
            images: List of images

        Returns:
            List of prediction result dictionaries
        """
        results = []
        for image in images:
            result = self.predict(image)
            results.append(result)
        return results

    def predict_video(
        self,
        video_path: str,
        output_path: Optional[str] = None,
        frame_skip: int = 5
    ) -> List[Dict[str, Any]]:
        """
        Process video and generate predictions.

        Args:
            video_path: Path to video file
            output_path: Optional path to save annotated video
            frame_skip: Process every Nth frame

        Returns:
            List of predictions per processed frame
        """
        try:
            import cv2
        except ImportError:
            raise ImportError("OpenCV (cv2) is required for video processing")

        if not os.path.exists(video_path):
            raise FileNotFoundError(f"Video not found: {video_path}")

        cap = cv2.VideoCapture(video_path)
        fps = int(cap.get(cv2.CAP_PROP_FPS))
        width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
        height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

        print(f"📹 Processing video: {fps}fps, {width}x{height}, {total_frames} frames")

        predictions = []
        frame_count = 0
        processed_count = 0

        out = None
        if output_path:
            fourcc = cv2.VideoWriter_fourcc(*'mp4v')
            out = cv2.VideoWriter(output_path, fourcc, fps, (width, height))

        while True:
            ret, frame = cap.read()
            if not ret:
                break

            if frame_count % frame_skip == 0:
                # Convert BGR to RGB
                frame_rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)

                # Predict
                result = self.predict(frame_rgb)
                result['metadata']['frame_number'] = frame_count
                predictions.append(result)
                processed_count += 1

                # Draw prediction on frame
                if output_path:
                    pred = result['prediction']
                    conf = result['confidence']

                    # Color based on risk
                    risk = result['risk_score']
                    if risk > 0.7:
                        color = (0, 0, 255)  # Red - High risk
                    elif risk > 0.4:
                        color = (0, 255, 255)  # Yellow - Medium risk
                    else:
                        color = (0, 255, 0)  # Green - Low risk

                    cv2.putText(
                        frame,
                        f"{pred}: {conf:.1f}%",
                        (10, 30),
                        cv2.FONT_HERSHEY_SIMPLEX,
                        0.8,
                        color,
                        2,
                        cv2.LINE_AA
                    )
                    out.write(frame)

            frame_count += 1

        cap.release()
        if out:
            out.release()

        print(f"✅ Processed {processed_count} frames")
        return predictions



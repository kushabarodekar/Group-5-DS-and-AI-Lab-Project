# 5. Risk Calculator
# ============================================
class RiskCalculator:
    """Risk score calculation."""

    # Risk mapping for each class
    RISK_MAPPING = {
        'safe_driving': 0.05,
        'turning': 0.20,
        'talking_phone': 0.60,
        'other_activities': 0.70,
        'texting_phone': 0.85
    }

    @classmethod
    def calculate_risk(cls, predicted_class: str, confidence: float) -> float:
        """
        Calculate risk score based on prediction and confidence.

        Args:
            predicted_class: Predicted class name
            confidence: Confidence score (0-100)

        Returns:
            Risk score (0-1)
        """
        base_risk = cls.RISK_MAPPING.get(predicted_class, 0.50)
        confidence_factor = confidence / 100.0
        return base_risk * confidence_factor



# 7. Module Adapter (For Module Manager Integration)
# ============================================
class DriverActivityAdapter:
    """
    Adapter for integration with the Driver Wellness Module Manager.
    """

    def __init__(
        self,
        model_path: str,
        device: Optional[str] = None
    ):
        """
        Initialize the adapter.

        Args:
            model_path: Path to model checkpoint
            device: Device to run inference on
        """
        self.config = InferenceConfig(device=device or InferenceConfig.device)
        self.predictor = DriverActivityPredictor(
            model_path,
            config=self.config,
            lazy_load=True
        )

    def warmup(self) -> None:
        """Warmup the model."""
        self.predictor.warmup()

    def unload(self) -> None:
        """Unload the model."""
        self.predictor.unload()

    def predict(self, image: Union[str, np.ndarray, Image.Image]) -> Dict[str, Any]:
        """
        Predict driver activity.

        Args:
            image: Input image

        Returns:
            Standard output contract dictionary
        """
        result = self.predictor.predict(image)

        # Ensure standard format
        return {
            'module': 'Driver Activity Classification',
            'prediction': result['prediction'],
            'confidence': result['confidence'],
            'risk_score': result['risk_score'],
            'metadata': result['metadata']
        }

    def predict_batch(self, images: List) -> List[Dict[str, Any]]:
        """Predict for multiple images."""
        return self.predictor.predict_batch(images)



def draw_prediction(frame, result, class_names, confidence_threshold=0.5):
    """
    Draw prediction on video frame.
    """
    frame_copy = frame.copy()
    height, width = frame_copy.shape[:2]

    # Get prediction
    predicted_class = result['class']
    confidence = result['confidence']

    # Set color based on confidence
    if confidence > 80:
        color = (0, 255, 0)  # Green - High confidence
    elif confidence > 60:
        color = (0, 255, 255)  # Yellow - Medium confidence
    else:
        color = (0, 0, 255)  # Red - Low confidence

    # Draw background rectangle
    text = f"{predicted_class}: {confidence:.1f}%"
    (text_width, text_height), baseline = cv2.getTextSize(
        text, cv2.FONT_HERSHEY_SIMPLEX, 0.8, 2
    )

    cv2.rectangle(
        frame_copy,
        (10, 10),
        (10 + text_width + 20, 10 + text_height + 20),
        (0, 0, 0),
        -1
    )

    # Draw prediction text
    cv2.putText(
        frame_copy,
        text,
        (20, 10 + text_height + 10),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.8,
        color,
        2,
        cv2.LINE_AA
    )

    # Draw class probabilities bar (optional)
    bar_x = 20
    bar_y = 10 + text_height + 30
    bar_width = 200
    bar_height = 15

    # Draw all class probabilities as small bars
    for i, (name, prob) in enumerate(zip(class_names, result['probabilities'])):
        prob_percent = prob * 100
        bar_color = (0, 255, 0) if i == result['predicted_index'] else (100, 100, 100)

        # Only show if probability > 5%
        if prob_percent > 5:
            cv2.rectangle(
                frame_copy,
                (bar_x, bar_y + i * 20),
                (bar_x + int(bar_width * (prob_percent / 100)), bar_y + i * 20 + 10),
                bar_color,
                -1
            )

    return frame_copy


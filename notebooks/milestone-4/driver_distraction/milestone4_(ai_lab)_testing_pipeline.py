def process_video(input_video_path, output_video_path, model, device,
                  class_names, transform, frame_skip=5, confidence_threshold=0.5):
    """
    Process video and add predictions to frames.
    """
    # Check if input video exists
    if not os.path.exists(input_video_path):
        print(f"❌ Video not found: {input_video_path}")
        return None

    # Open video
    cap = cv2.VideoCapture(input_video_path)

    # Get video properties
    fps = int(cap.get(cv2.CAP_PROP_FPS))
    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    print(f"\n📹 Video Information:")
    print(f"   - FPS: {fps}")
    print(f"   - Resolution: {width}x{height}")
    print(f"   - Total Frames: {total_frames}")
    print(f"   - Frame Skip: {frame_skip}")

    # Create video writer
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(output_video_path, fourcc, fps, (width, height))

    # Process frames
    frame_count = 0
    processed_count = 0
    predictions = []
    start_time = time.time()

    print(f"\n🔍 Processing video...")

    while True:
        ret, frame = cap.read()
        if not ret:
            break

        # Skip frames
        if frame_count % frame_skip == 0:
            # Get prediction
            result = predict_frame(frame, model, transform, device, class_names)
            predictions.append(result)

            # Draw prediction on frame
            frame_with_pred = draw_prediction(frame, result, class_names, confidence_threshold)
            out.write(frame_with_pred)

            processed_count += 1

            # Progress update
            if processed_count % 50 == 0:
                print(f"   Processed: {processed_count} frames")

        frame_count += 1

    # Release resources
    cap.release()
    out.release()

    end_time = time.time()
    processing_time = end_time - start_time

    print(f"\n✅ Video processing complete!")
    print(f"   - Total frames processed: {processed_count}")
    print(f"   - Processing time: {processing_time:.2f} seconds")
    print(f"   - Average FPS: {processed_count / processing_time:.2f}")
    print(f"   - Output saved to: {output_video_path}")

    return predictions

